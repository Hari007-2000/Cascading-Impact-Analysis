"""## Step 7 (optional) — All-industries structural multipliers

Since most industries in a PIOT often have zero baseline final demand, a
"% of current demand" shock is undefined for them. This computes the
scale-independent **total output multiplier** (backward linkage) for every
industry via a unit demand shock — the standard IO-theory approach.

"""

def all_industries_multipliers(net):
    L, industries = net['L'], net['industries']
    backward_raw = L.sum(axis=0)
    forward_raw = L.sum(axis=1)   # demand-side proxy for forward linkage
    self_effect = np.diag(L)
    return pd.DataFrame({
        'industry': industries,
        'backward_linkage_raw': backward_raw,
        'backward_linkage_norm': backward_raw / backward_raw.mean(),
        'forward_sensitivity_norm': forward_raw / forward_raw.mean(),
        'self_loop_coef': net['self_loop_coef'],
    }).set_index('industry').sort_values('backward_linkage_raw', ascending=False)


