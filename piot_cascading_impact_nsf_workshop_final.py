"""## Step 3 — Run a demand shock

Pick a target industry and a % increase in its final demand. Everything
downstream (industrial cascade, tiers, waste) follows from this one shock.

"""

TARGET_INDUSTRY = "Acetaminophen"   # change to any industry name in `industries`
PCT_INCREASE = 0.15                # 25% increase in final demand

def demand_shock(df, industries, net, target_industry, pct_increase):
    L = net['L']
    d0 = df.loc[industries, 'FINAL_DEMAND'].values.astype(float)
    idx = industries.index(target_industry)
    d1 = d0.copy()
    d1[idx] = d0[idx] * (1 + pct_increase)
    delta_d = d1 - d0

    delta_x = L @ delta_d
    out = pd.DataFrame({'industry': industries, 'x0_baseline': net['x0'], 'delta_x': delta_x}).set_index('industry')
    out['pct_change'] = 100 * out['delta_x'] / out['x0_baseline']
    return out, delta_d


results, delta_d = demand_shock(df0, industries, net, TARGET_INDUSTRY, PCT_INCREASE)
print(f"Total network Delta x from {int(PCT_INCREASE*100)}% shock to {TARGET_INDUSTRY}: "
      f"{results['delta_x'].sum():,.0f} kg\n")
results.reindex(results['delta_x'].abs().sort_values(ascending=False).index).head(15)

"""## Step 4 — Tier decomposition

Split the cascade by propagation depth (own demand / direct / indirect / deeper).
"""

def tier_decomposition(net, delta_d):
    A, L, industries = net['A'], net['L'], net['industries']
    delta_x = L @ delta_d
    A2 = A @ A
    tier0 = delta_d.copy()
    tier1 = A @ delta_d
    tier2 = A2 @ delta_d
    tier3plus = delta_x - (tier0 + tier1 + tier2)
    return pd.DataFrame({'industry': industries, 'tier0_own_demand': tier0, 'tier1_direct': tier1,
                          'tier2_indirect': tier2, 'tier3plus_indirect': tier3plus, 'total': delta_x}).set_index('industry')


tiers = tier_decomposition(net, delta_d)
tiers.reindex(tiers['total'].abs().sort_values(ascending=False).index).head(10)

"""## Step 5 — Waste cascade

Weight the output cascade by each industry's baseline waste intensity (kg waste / kg output).
"""

def waste_cascade(df, industries, net, delta_x):
    x0 = net['x0']
    waste0 = df.loc[industries, 'WASTE'].values.astype(float)
    waste_intensity = np.divide(waste0, x0, out=np.zeros_like(waste0), where=x0 > 0)
    delta_waste = delta_x * waste_intensity
    return pd.DataFrame({'industry': industries, 'waste_intensity': waste_intensity,
                          'delta_waste': delta_waste}).set_index('industry')


waste_df = waste_cascade(df0, industries, net, results['delta_x'].values)
