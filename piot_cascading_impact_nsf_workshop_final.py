"""## Step 2 — Build the network (A matrix + Leontief inverse)

`a_ij = z_ij / x_j`, where `x_j` is industry j's total output (row sum across
all industries + ROE + EXPORTS + FINAL_DEMAND + WASTE).



"""

META_COLS = ['ROE', 'EXPORTS', 'FINAL_DEMAND', 'WASTE']


def load_piot(path):
    """Load a raw PIOT CSV, return (dataframe, list of industry names)."""
    df = pd.read_csv(path, index_col=0).fillna(0.0)
    industries = [c for c in df.columns if c not in META_COLS and not c.startswith('Unnamed:')]
    return df, industries


def build_network(df, industries, remove_self_loops=False):
    """
    Build Z, x0, A, L from a loaded PIOT dataframe.

    Returns a dict with keys: Z, x0, A, L, industries, spectral_radius,
    self_loop_coef.
    """
    Z = df.loc[industries, industries].values.astype(float)
    x0 = df.loc[industries, industries + META_COLS].sum(axis=1).values.astype(float)
    x0 = np.where(x0 == 0, 1e-9, x0)

    A = Z / x0[np.newaxis, :]
    self_loop_coef = np.diag(A).copy()  # always retained as a diagnostic

    if remove_self_loops:
         np.fill_diagonal(A, 0.0)

    n = len(industries)
    I = np.eye(n)
    spectral_radius = float(np.max(np.abs(np.linalg.eigvals(A))))
    if spectral_radius >= 1.0:
        raise ValueError(
            f"Spectral radius of A is {spectral_radius:.4f} >= 1: the Leontief "
            "inverse does not exist (network not productive). This usually "
            "means a cell is a genuine data error rather than real recycling "
            "-- run the outlier screen in Step 2b before assuming the network "
            "itself is at fault."
        )
    L = np.linalg.inv(I - A)

    return {'Z': Z, 'x0': x0, 'A': A, 'L': L, 'industries': industries,
            'spectral_radius': spectral_radius,'self_loop_coef': self_loop_coef}


